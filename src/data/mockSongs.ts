export const searchSongs = (query: string, gender: string = "all", maxResults: number = 25, pageToken?: string): { songs: Song[]; nextPageToken?: string } => {
  if (!query.trim()) return { songs: [] };
  
  // For testing pagination, create a large dataset by duplicating songs
  let filtered = mockSongs;
  
  // Create enough data for pagination testing (at least 50 songs)
  while (filtered.length < 50) {
    filtered = [...filtered, ...mockSongs.map(song => ({
      ...song,
      id: `${song.id}_dup_${Math.floor(filtered.length / mockSongs.length)}`,
      title: `${song.title} (Copy ${Math.floor(filtered.length / mockSongs.length)})`
    }))];
  }
  
  // Apply gender filtering but keep enough results
  if (gender === "male") {
    const maleResults = filtered.filter(song => 
      song.title.includes("男声") || song.artist.includes("Male")
    );
    // If not enough male results, keep all results for pagination testing
    if (maleResults.length >= 30) {
      filtered = maleResults;
    }
    // Otherwise keep filtered as is (all results)
  } else if (gender === "female") {
    const femaleResults = filtered.filter(song => 
      song.title.includes("女声") || song.artist.includes("Female")
    );
    // If not enough female results, keep all results for pagination testing
    if (femaleResults.length >= 30) {
      filtered = femaleResults;
    }
    // Otherwise keep filtered as is (all results)
  }
  
  // Simulate pagination with pageToken
  let startIndex = 0;
  if (pageToken) {
    // Parse pageToken as base64 encoded start index
    try {
      startIndex = parseInt(atob(pageToken), 10) || 0;
    } catch {
      startIndex = 0;
    }
  }
  
  const endIndex = startIndex + maxResults;
  const paginatedResults = filtered.slice(startIndex, endIndex);
  
  // Generate next page token if there are more results
  const nextPageToken = endIndex < filtered.length ? btoa(endIndex.toString()) : undefined;
  
  // Debug logging
  console.log('Mock pagination:', {
    query,
    totalFiltered: filtered.length,
    startIndex,
    endIndex,
    maxResults,
    returnedResults: paginatedResults.length,
    nextPageToken,
    hasMore: endIndex < filtered.length
  });
  
  return {
    songs: paginatedResults,
    nextPageToken
  };
};